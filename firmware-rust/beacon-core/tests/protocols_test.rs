#[test]
fn test_all_station_encoders_match_c_oracle() {
    let test_cases = [
        (TimeStation::Bpc, &ST_0_EXPECTED, "BPC"),
        (TimeStation::Wwvb, &ST_1_EXPECTED, "WWVB"),
        (TimeStation::Msf, &ST_2_EXPECTED, "MSF"),
        (TimeStation::Dcf77, &ST_3_EXPECTED, "DCF77"),
        (TimeStation::Jjy40, &ST_4_EXPECTED, "JJY40"),
        (TimeStation::Jjy60, &ST_5_EXPECTED, "JJY60"),
    ];

    for (station, expected_buf, name) in test_cases {
        let (buf, num_ticks) = generate_frame(station, TEST_EPOCH, 0, 0);
        assert_eq!(num_ticks, 1200, "Station {} tick count mismatch", name);
        assert_eq!(&buf[..], &expected_buf[..], "Station {} bitstream mismatch", name);
    }
}
